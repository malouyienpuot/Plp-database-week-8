-- V1: Core entities and integrity constraints.
CREATE TABLE tenants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE RESTRICT,
    full_name VARCHAR(160) NOT NULL,
    email VARCHAR(254) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('admin', 'trainer', 'student')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT app_users_tenant_email_uq UNIQUE (tenant_id, email),
    CONSTRAINT app_users_id_tenant_uq UNIQUE (id, tenant_id)
);

CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE RESTRICT,
    title VARCHAR(180) NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT courses_id_tenant_uq UNIQUE (id, tenant_id)
);

CREATE TABLE enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE RESTRICT,
    student_id BIGINT NOT NULL,
    course_id BIGINT NOT NULL,
    enrolled_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    status VARCHAR(20) NOT NULL DEFAULT 'enrolled'
        CHECK (status IN ('enrolled', 'completed', 'withdrawn')),
    CONSTRAINT enrollments_student_tenant_fk
        FOREIGN KEY (student_id, tenant_id) REFERENCES app_users(id, tenant_id),
    CONSTRAINT enrollments_course_tenant_fk
        FOREIGN KEY (course_id, tenant_id) REFERENCES courses(id, tenant_id),
    CONSTRAINT enrollments_tenant_student_course_uq
        UNIQUE (tenant_id, student_id, course_id),
    CONSTRAINT enrollments_id_tenant_uq UNIQUE (id, tenant_id)
);

CREATE TABLE attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE RESTRICT,
    enrollment_id BIGINT NOT NULL,
    class_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('present', 'absent', 'late', 'excused')),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT attendance_enrollment_tenant_fk
        FOREIGN KEY (enrollment_id, tenant_id) REFERENCES enrollments(id, tenant_id),
    CONSTRAINT attendance_tenant_enrollment_date_uq UNIQUE (tenant_id, enrollment_id, class_date)
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT,
    table_name TEXT NOT NULL,
    operation TEXT NOT NULL,
    row_id TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    db_user TEXT NOT NULL DEFAULT session_user,
    old_data JSONB,
    new_data JSONB
);
